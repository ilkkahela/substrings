#include "completions.h"
#include "cli.h"
#include <format>
#include <iterator>
#include <string>
#include <vector>

using namespace std;

namespace {

bool takesFile(const Option& option) {
    return option.value_name == "FILE";
}

// Replaces each character in `special` with a backslash and itself, and a
// single quote with '\'' (close, escaped quote, reopen).
string quoteBody(string_view s, string_view special) {
    string result;
    for (char c : s) {
        if (c == '\'') result += R"('\'')";
        else if (special.contains(c)) result += {'\\', c};
        else result += c;
    }
    return result;
}

string join(const vector<string>& words, string_view separator) {
    string result;
    for (const auto& word : words) {
        if (!result.empty()) result += separator;
        result += word;
    }
    return result;
}

// The words an option is offered as. One that needs a value is offered as
// "--top=", so the cursor stays after the "="; an optional one both ways.
vector<string> offeredWords(const Option& option) {
    vector<string> words;
    if (option.arity != Arity::None) words.push_back(format("{}=", option.name));
    if (option.arity != Arity::Required) words.emplace_back(option.name);
    if (!option.alias.empty()) words.emplace_back(option.alias);
    return words;
}

// The words right before an option's value, as bash sees them: "--opt=" (the
// script rejoins the "=" that bash splits off) and, for a required value,
// the option itself ("--top N", "-n N").
vector<string> valuePrefixes(const Option& option) {
    vector<string> prefixes;
    if (option.arity == Arity::None) return prefixes;
    prefixes.push_back(format("{}=", option.name));
    if (option.arity == Arity::Required) {
        prefixes.emplace_back(option.name);
        if (!option.alias.empty()) prefixes.emplace_back(option.alias);
    }
    return prefixes;
}

// One arm of the script's `case $opt in`.
string caseArm(const vector<string>& patterns, string_view body) {
    return format("        {})\n{}            return ;;\n", join(patterns, "|"), body);
}

void append(vector<string>& to, const vector<string>& more) {
    to.insert(to.end(), more.begin(), more.end());
}

string bashScript() {
    vector<string> words, file_prefixes, free_prefixes;
    string choice_arms;
    for (const auto& option : options()) {
        append(words, offeredWords(option));
        auto prefixes = valuePrefixes(option);
        if (prefixes.empty()) continue;

        if (takesFile(option))
            append(file_prefixes, prefixes);
        else if (!option.choices.empty())
            choice_arms += caseArm(prefixes, format(
                "            mapfile -t COMPREPLY < <(compgen -W \"{}\" -- \"$cur\")\n",
                option.choices));
        else
            append(free_prefixes, prefixes);
    }

    string cases = caseArm(file_prefixes,
                           "            compopt -o filenames\n"
                           "            mapfile -t COMPREPLY < <(compgen -f -- \"$cur\")\n");
    cases += choice_arms;
    cases += caseArm(free_prefixes, "            # a value with nothing to suggest\n");

    return format(R"(# bash completion for substrings. Generated by: substrings --completions=bash
# Load it with: source <(substrings --completions=bash)
_substrings() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}} opt i
    for ((i = 1; i < COMP_CWORD; i++)); do
        [[ ${{COMP_WORDS[i]}} == -- ]] && return  # input text from here on
    done

    # bash splits "--opt=value" into "--opt", "=" and "value".
    if [[ $cur == = ]]; then
        opt=$prev= cur=
    elif [[ $prev == = ]] && ((COMP_CWORD >= 2)); then
        opt=${{COMP_WORDS[COMP_CWORD-2]}}=
    else
        opt=$prev
    fi

    case $opt in
{}    esac

    if [[ $cur == -* ]]; then
        mapfile -t COMPREPLY < <(compgen -W "{}" -- "$cur")
        [[ ${{COMPREPLY[0]}} == *= ]] && compopt -o nospace
    fi
}}
complete -F _substrings substrings
)", cases, join(words, " "));
}

string zshScript() {
    vector<string> specs;
    for (const auto& option : options()) {
        string help = quoteBody(option.help, R"(\[])");
        string action = takesFile(option)        ? "_files"
                        : !option.choices.empty() ? format("({})", option.choices)
                                                  : " ";
        string exclusive = option.alias.empty()
                               ? ""
                               : format("({} {})", option.alias, option.name);
        auto spec = [&](string_view name, string_view value_form) {
            switch (option.arity) {
                case Arity::None:
                    return format("'{}{}[{}]'", exclusive, name, help);
                case Arity::Required:
                    return format("'{}{}{}[{}]:{}:{}'", exclusive, name, value_form, help,
                                  option.value_name, action);
                case Arity::Optional:
                    return format("'{}{}=-[{}]::{}:{}'", exclusive, name, help,
                                  option.value_name, action);
            }
            return string();
        };
        specs.push_back(spec(option.name, "="));  // --top=N or --top N
        if (!option.alias.empty()) specs.push_back(spec(option.alias, ""));  // -n N
    }

    return format(R"(#compdef substrings
# zsh completion for substrings. Generated by: substrings --completions=zsh
# Install it as _substrings in a directory on $fpath, or load it with:
#   source <(substrings --completions=zsh)
_substrings() {{
    _arguments -S \
        {}
}}
if [[ $funcstack[1] == _substrings ]]; then
    _substrings "$@"
else
    compdef _substrings substrings
fi
)", join(specs, " \\\n        "));
}

string fishScript() {
    string script = "# fish completion for substrings. Generated by: substrings --completions=fish\n"
                    "complete -c substrings -f  # INPUT is text, not a file name\n";
    for (const auto& option : options()) {
        string line = "complete -c substrings";
        if (option.name.starts_with("--")) line += format(" -l {}", option.name.substr(2));
        if (!option.alias.empty()) line += format(" -s {}", option.alias.substr(1));
        if (option.arity == Arity::Required) line += takesFile(option) ? " -r -F" : " -x";
        if (!option.choices.empty()) line += format(" -a '{}'", option.choices);
        line += format(" -d '{}'\n", quoteBody(option.help, "\\"));
        script += line;
    }
    return script;
}

} // namespace

string completionScript(string_view shell) {
    if (shell == "bash") return bashScript();
    if (shell == "zsh") return zshScript();
    if (shell == "fish") return fishScript();
    return {};
}
